type VideoSeed = Omit<
  Video,
  "id" | "research" | "script" | "packaging" | "metrics" | "aiAnalysis" | "createdAt" | "updatedAt"
> & {
  research?: ResearchData | null;
  script?: ScriptData | null;
  packaging?: PackagingData | null;
  metrics?: Video["metrics"];
  aiAnalysis?: Video["aiAnalysis"];
};

function video(v: VideoSeed): Video {
  const now = new Date().toISOString();
  return {
    id: uid("vid"),
    research: null,
    script: null,
    packaging: null,
    metrics: null,
    aiAnalysis: null,
    createdAt: now,
    updatedAt: now,
    ...v,
  };
}

